//
//  ProfileScript.swift — a profile as the POSIX sh script that sets it up in
//  a VM, run as root by MonadHost over the VM's ssh.
//
//  Each step first looks for what it would install and does nothing when it
//  is all there, so running the script again changes nothing (Node.js moves
//  to a newer LTS when one is out). Progress is told by marker lines on
//  stdout (see ProfileProgress), and what each step does by "› " lines; the
//  first failing step stops the run. Every name was validated with the
//  profile, and is quoted anyway.
//
//  The script comes on the shell's stdin, so all of it is one function, read
//  whole before it runs, and run with stdin from /dev/null: a command that
//  reads (a prompt) cannot swallow the steps after it.
//
//  Node.js comes from nodejs.org, fetched in the VM: the newest LTS for its
//  CPU from the release index, checked against the release's checksum file
//  (trust: HTTPS, as for npm), unpacked under /opt/monad and linked into
//  /usr/local/bin so every shell, service and user has it.
//

import Foundation

/// What a marker line says.
enum ProfileProgress: Equatable, Sendable {
    case started(String)
    case finished(String)
    case failed(String, String)
    case allDone
    /// The script's process id: as a session leader (setsid), its group's too.
    case pid(Int)

    static let prefix = "@@monad "

    static func parse(_ line: String) -> ProfileProgress? {
        guard line.hasPrefix(prefix) else { return nil }
        let words = line.dropFirst(prefix.count).split(separator: " ", maxSplits: 3, omittingEmptySubsequences: false)
            .map(String.init)
        if words == ["finished"] { return .allDone }
        if words.count == 2, words[0] == "pid", words[1].allSatisfy(\.isNumber), let n = Int(words[1]), n > 1 {
            return .pid(n)
        }
        guard words.count >= 3, words[0] == "step", ProfileConfig.isID(words[1]) else { return nil }
        switch (words[2], words.count) {
        case ("start", 3): return .started(words[1])
        case ("done", 3): return .finished(words[1])
        case ("failed", 4): return .failed(words[1], words[3])
        default: return nil
        }
    }
}

enum ProfileScript {
    static let nodeDist = "https://nodejs.org/dist"

    struct Invalid: Error, LocalizedError {
        let message: String
        var errorDescription: String? { message }
    }

    /// `root` prefixes every path the script installs to ("" in a VM; tests
    /// use a temporary directory).
    static func render(_ profile: ProfileConfig, packageManager: String, user: String,
                       root: String = "") throws -> String {
        guard user.range(of: #"\A[a-z_][a-z0-9_-]{0,31}\z"#, options: .regularExpression) != nil else {
            throw Invalid(message: "“\(user)” is not a user name.")
        }
        guard profile.supports(packageManager: packageManager) else {
            throw Invalid(message: "\(profile.name) has no packages for \(packageManager).")
        }
        var s = """
        #!/bin/sh
        # Monad profile \(profile.name) (\(profile.id)), generated by Monad. Each step skips
        # what is already set up, so running this again changes nothing.
        set -u
        monad_main() {
        # From /, not the login user's home: npm runs install scripts as the
        # owner of the directory it works in.
        cd / || exit 1
        # Its own session (setsid): Stop ends the whole group by this id.
        echo "@@monad pid $$"
        MONAD_USER=\(q(user))
        MONAD_ROOT=\(q(root))
        export MONAD_USER MONAD_ROOT
        DEBIAN_FRONTEND=noninteractive
        export DEBIAN_FRONTEND
        PATH="$MONAD_ROOT/usr/local/bin:$PATH"
        export PATH
        mkdir -p "$MONAD_ROOT/usr/local/bin"
        fail() { echo "@@monad step $1 failed $2"; exit 1; }
        need() { command -v "$2" >/dev/null 2>&1 || fail "$1" "$2 is not on PATH"; }
        say() { echo "› $*"; }

        """
        for step in profile.steps {
            let id = q(step.id)
            s += "echo \(q("@@monad step \(step.id) start"))\n"
            switch step.kind {
            case .packages:
                s += packages(step.packages?[packageManager] ?? [], manager: packageManager, step: id)
            case .runtime:
                guard step.runtime == "nodejs" else {
                    throw Invalid(message: "\(profile.name): Monad does not know the runtime \(step.runtime ?? "").")
                }
                s += node(step: id)
            case .npm:
                s += npm(step.npm ?? [], step: id)
            case .script:
                s += script(step.script ?? "", step: id)
            case nil:
                throw Invalid(message: "\(profile.name): step \(step.id) is not one thing.")
            }
            for c in step.commands ?? [] { s += "need \(id) \(q(c))\n" }
            s += "echo \(q("@@monad step \(step.id) done"))\n"
        }
        s += "echo '@@monad finished'\n}\nmonad_main </dev/null\n"
        return s
    }

    private static func q(_ s: String) -> String { "'" + s.replacingOccurrences(of: "'", with: #"'\''"#) + "'" }

    /// What each package manager is told: whether a package is installed,
    /// whether it can be installed, refreshing its lists, installing.
    private static func manager(_ m: String) -> (installed: String, available: String, refresh: String?, install: String) {
        switch m {
        case "apt":
            return ("dpkg-query -W -f='${Status}' \"$c\" 2>/dev/null | grep -q 'install ok installed'",
                    "apt-cache show \"$a\" >/dev/null 2>&1",
                    "apt-get update -q",
                    "apt-get install -y -q --no-install-recommends")
        case "dnf":
            return ("rpm -q --quiet \"$c\" 2>/dev/null", "dnf -q info \"$a\" >/dev/null 2>&1", nil, "dnf install -y")
        default: // zypper
            return ("rpm -q --quiet \"$c\" 2>/dev/null",
                    "zypper --non-interactive -q search -x --match-exact \"$a\" >/dev/null 2>&1", nil,
                    "zypper --non-interactive install --no-recommends")
        }
    }

    /// Installs what is missing; "a|b" is installed if any of them is, else
    /// the first one the distro has is installed.
    private static func packages(_ names: [String], manager m: String, step: String) -> String {
        let pm = manager(m)
        let list = names.map(q).joined(separator: " ")
        let tool = pm.install.split(separator: " ").first.map(String.init) ?? m
        var s = """
        missing=''
        for p in \(list); do
          have=''
          for c in $(printf '%s' "$p" | tr '|' ' '); do \(pm.installed) && have=1 && break; done
          [ -n "$have" ] || missing="$missing $p"
        done
        if [ -z "$missing" ]; then
          say \(q("Already installed: " + names.joined(separator: " ")))
        else

        """
        if let refresh = pm.refresh {
            s += "  say 'Refreshing the package lists'\n  \(refresh) || fail \(step) \(q(refresh + " failed"))\n"
        }
        s += """
          pick=''
          for p in $missing; do
            c=''
            for a in $(printf '%s' "$p" | tr '|' ' '); do
              case "$p" in *'|'*) \(pm.available) || continue ;; esac
              c="$a"
              break
            done
            [ -n "$c" ] || fail \(step) "none of $p can be installed"
            pick="$pick $c"
          done
          say "Installing$pick"
          \(pm.install) $pick || fail \(step) \(q("\(tool) install failed"))
        fi

        """
        return s
    }

    /// The newest Node.js LTS for the VM's CPU, unless it is there already.
    private static func node(step: String) -> String {
        """
        case "$(uname -m)" in
          aarch64|arm64) arch=arm64 ;;
          x86_64|amd64) arch=x64 ;;
          *) fail \(step) "no Node.js build for $(uname -m)" ;;
        esac
        tmp=$(mktemp -d) || fail \(step) 'cannot make a temporary directory'
        say 'Finding the latest Node.js LTS'
        # Saved, then read (awk stops at the first match: reading from a pipe would cut curl off).
        curl -fsSL \(q(nodeDist + "/index.tab")) -o "$tmp/index.tab" || { rm -rf "$tmp"; fail \(step) 'the Node.js release index could not be fetched'; }
        # index.tab: version, date, files, ..., lts (10th column, "-" for Current); newest first.
        version=$(awk -F '\t' -v want="linux-$arch" \\
          'NR > 1 && $10 != "-" && index("," $3 ",", "," want ",") { print $1; exit }' "$tmp/index.tab")
        printf '%s\n' "$version" | grep -Eq '^v[0-9]+[.][0-9]+[.][0-9]+$' || { rm -rf "$tmp"; fail \(step) 'no Node.js LTS release found'; }
        dir="$MONAD_ROOT/opt/monad/node-$version"
        if [ -x "$dir/bin/node" ]; then
          say "Node.js $version is installed"
        else
          say "Downloading Node.js $version"
          file="node-$version-linux-$arch.tar.xz"
          curl -fsSL \(q(nodeDist + "/"))"$version/SHASUMS256.txt" -o "$tmp/SHASUMS256.txt" \\
            && curl -fsSL \(q(nodeDist + "/"))"$version/$file" -o "$tmp/$file" \\
            || { rm -rf "$tmp"; fail \(step) 'the Node.js download failed'; }
          (cd "$tmp" && awk -v f="$file" '$2 == f' SHASUMS256.txt | grep -q . \\
            && awk -v f="$file" '$2 == f' SHASUMS256.txt | sha256sum -c - >/dev/null 2>&1) \\
            || { rm -rf "$tmp"; fail \(step) 'the Node.js download does not match its checksum'; }
          rm -rf "$dir.part" && mkdir -p "$dir.part" \\
            && tar -xJf "$tmp/$file" -C "$dir.part" --strip-components=1 \\
            || { rm -rf "$tmp" "$dir.part"; fail \(step) 'the Node.js archive could not be unpacked'; }
          mv "$dir.part" "$dir" || { rm -rf "$tmp"; fail \(step) 'cannot move Node.js into place'; }
        fi
        rm -rf "$tmp"
        for b in node npm npx; do
          ln -sfn "$dir/bin/$b" "$MONAD_ROOT/usr/local/bin/$b" || fail \(step) "cannot link $b"
        done
        for old in "$MONAD_ROOT"/opt/monad/node-v*; do
          [ "$old" = "$dir" ] || [ ! -d "$old" ] || rm -rf "$old"
        done

        """
    }

    private static func npm(_ specs: [String], step: String) -> String {
        """
        missing=''
        for p in \(specs.map(q).joined(separator: " ")); do
          npm ls -g --prefix "$MONAD_ROOT/usr/local" --depth=0 "$p" >/dev/null 2>&1 || missing="$missing $p"
        done
        if [ -z "$missing" ]; then
          say \(q("Already installed: " + specs.joined(separator: " ")))
        else
          say "Installing with npm:$missing"
          npm install -g --prefix "$MONAD_ROOT/usr/local" $missing || fail \(step) 'npm install failed'
        fi

        """
    }

    private static func script(_ text: String, step: String) -> String {
        var delimiter: String
        repeat {
            delimiter = "MONAD_SCRIPT_" + String(UInt64.random(in: 0...UInt64.max), radix: 16, uppercase: true)
        } while text.contains(delimiter)
        let body = text.hasSuffix("\n") ? text : text + "\n"
        return """
        f=$(mktemp) || fail \(step) 'cannot make a temporary file'
        say 'Running the script'
        cat > "$f" <<'\(delimiter)'
        \(body)\(delimiter)
        sh "$f"
        rc=$?
        rm -f "$f"
        [ "$rc" -eq 0 ] || fail \(step) "the script ended with status $rc"

        """
    }
}
