#!/usr/bin/env python3
"""Generate Monad/Backend/vt/mnd_wcwidth_tables.h from Python's unicodedata.

Usage: python3 Tools/gen_wcwidth.py > Monad/Backend/vt/mnd_wcwidth_tables.h

Zero width: general categories Mn, Me, Cf (except U+00AD), Hangul medial/final
jamo (U+1160-U+11FF, U+D7B0-U+D7FF) and U+200B.
Wide: East_Asian_Width W or F.
"""
import sys
import unicodedata

MAX_CP = 0x10FFFF


def ranges(pred):
    out = []
    start = None
    for cp in range(MAX_CP + 2):
        hit = cp <= MAX_CP and pred(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def is_zero(cp):
    if cp == 0x00AD:
        return False
    if 0x1160 <= cp <= 0x11FF or 0xD7B0 <= cp <= 0xD7FF or cp == 0x200B:
        return True
    return unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf")


def is_wide(cp):
    if 0xD800 <= cp <= 0xDFFF:
        return False
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F")


def emit(name, rs):
    print(f"static const mnd_range {name}[] = {{")
    for a, b in rs:
        print(f"    {{0x{a:05X}, 0x{b:05X}}},")
    print("};")


def main():
    print("/* Generated by Tools/gen_wcwidth.py from Unicode "
          f"{unicodedata.unidata_version}. Do not edit. */")
    print("#ifndef MND_WCWIDTH_TABLES_H")
    print("#define MND_WCWIDTH_TABLES_H")
    print()
    print("typedef struct { unsigned int lo, hi; } mnd_range;")
    print()
    emit("mnd_zero_width", ranges(is_zero))
    print()
    emit("mnd_wide", ranges(is_wide))
    print()
    print("#endif")


if __name__ == "__main__":
    sys.exit(main())
